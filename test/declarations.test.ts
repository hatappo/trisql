import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { after, before, describe, it } from "node:test";
import { fileURLToPath } from "node:url";
import type { Describer } from "../src/analysis/describer.ts";
import { openPgliteDescriber } from "../src/analysis/pglite.ts";
import { declarationPath, writeDeclarations } from "../src/generate/declarations.ts";

const root = fileURLToPath(new URL("..", import.meta.url));
const DDL = "CREATE TABLE users (id bigserial PRIMARY KEY, email text NOT NULL, name text);";

describe("declarations", () => {
  let describer: Describer;
  let dir: string;
  before(async () => {
    describer = await openPgliteDescriber([DDL]);
    dir = mkdtempSync(join(tmpdir(), "trisql-decl-"));
  });
  after(async () => {
    await describer.close();
    rmSync(dir, { recursive: true, force: true });
  });

  it("writes a .d.sql.ts beside each .sql with the virtual module's types", async () => {
    const sql = join(dir, "get-user.sql");
    writeFileSync(sql, "/*:doc one user */\nSELECT id, email, name FROM users WHERE id = /*$id*/1\n");
    const first = await writeDeclarations([sql], describer);
    assert.deepEqual(first.failed, []);
    assert.equal(first.written.length, 1);
    const text = readFileSync(declarationPath(sql), "utf8");
    assert.match(text, /^\/\/ Generated by trisql from get-user\.sql\. Do not edit\.\n/);
    assert.match(text, /export type Params = \{ id: string \| number \| bigint \};/);
    assert.match(text, /export type Row = \{ id: string; email: string; name: string \| null \};/);
    assert.match(text, /\/\*\* one user \*\//);
    const second = await writeDeclarations([sql], describer);
    assert.deepEqual(second.written, []);
    assert.equal(second.unchanged.length, 1);
  });

  it("skips files the database refuses and reports why", async () => {
    const bad = join(dir, "bad.sql");
    writeFileSync(bad, "SELECT nope FROM users");
    const result = await writeDeclarations([bad], describer);
    assert.equal(result.failed.length, 1);
    assert.match(result.failed[0]?.message ?? "", /nope/);
  });

  it("gives TypeScript without a content mapper the same types", async () => {
    // content mapper なし（--runExternalCode なし、contentMappers なし）の tsc で、宣言ファイルだけで型が付くこと
    const project = join(dir, "project");
    mkdirSync(join(project, "node_modules"), { recursive: true });
    symlinkSync(root, join(project, "node_modules", "trisql"), "dir");
    writeFileSync(join(project, "package.json"), JSON.stringify({ type: "module" }));
    const sql = join(project, "get-user.sql");
    writeFileSync(sql, "SELECT id, email FROM users WHERE id = /*$id*/1\n");
    await writeDeclarations([sql], describer);
    writeFileSync(
      join(project, "tsconfig.json"),
      JSON.stringify({
        compilerOptions: {
          strict: true,
          noEmit: true,
          module: "nodenext",
          moduleResolution: "nodenext",
          allowArbitraryExtensions: true,
          types: [],
        },
        include: ["main.ts"],
      }),
    );
    writeFileSync(
      join(project, "main.ts"),
      [
        'import getUser from "./get-user.sql";',
        "declare const db: { query(text: string, values?: unknown[]): Promise<{ rows: unknown[] }> };",
        'const user = await getUser.maybeOne(db, { id: "1" });',
        "const email: string = user ? user.email : '';",
        "await getUser.run(db, { nope: 1 });",
        "console.log(email);",
        "",
      ].join("\n"),
    );
    const bin = join(root, "node_modules", "typescript", "bin", "tsc");
    const r = spawnSync(process.execPath, [bin, "-p", project, "--noEmit"], { encoding: "utf8", cwd: project });
    const errors = r.stdout.split("\n").filter((l) => l.includes("error TS"));
    assert.deepEqual(
      errors.map((l) => l.replace(/^.*main\.ts/, "main.ts")),
      [
        "main.ts(5,25): error TS2353: Object literal may only specify known properties, and 'nope' does not exist in type 'Params'.",
      ],
    );
  });
});
